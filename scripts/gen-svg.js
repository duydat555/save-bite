// Converts SVGs exported from Figma (assets/icons, assets/brand) into
// src/design-system/icons/svg-data.ts so they render via react-native-svg's SvgXml.
// Usage: node scripts/gen-svg.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dirs = ['assets/icons', 'assets/brand'];
const out = path.join(root, 'src/design-system/icons/svg-data.ts');

function walk(dir) {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs, { withFileTypes: true }).flatMap((e) => {
    const rel = path.join(dir, e.name);
    return e.isDirectory() ? walk(rel) : rel.endsWith('.svg') ? [rel] : [];
  });
}

const clean = (xml) =>
  xml
    .replace(/\s(style|preserveAspectRatio|overflow)="[^"]*"/g, '')
    .replace(/\sid="[^"]*"/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();

const entries = dirs
  .flatMap(walk)
  .sort()
  .map((f) => {
    const key = path.basename(f, '.svg');
    return `  '${key}': ${JSON.stringify(clean(fs.readFileSync(path.join(root, f), 'utf8')))},`;
  });

fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-svg.js — do not edit by hand.\nexport const svgData = {\n${entries.join('\n')}\n} as const;\n\nexport type SvgName = keyof typeof svgData;\n`,
);
console.log(`${entries.length} svgs -> ${path.relative(root, out)}`);
